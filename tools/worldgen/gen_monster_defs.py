"""Writes scripts/data/monster_defs.gd: every monster kind (sprites + base stats) by name, so the game can
spawn any of them in code (dungeon waves). Uses the same definitions the map generators use."""
import os
import w_forest  # noqa: F401  (obsidian golem)
import w_desert  # noqa: F401  (desert creatures)
import w_snow_assets  # noqa: F401  (snow creatures and beasts)
import w_field as WF
from w_common import ROOT


def gd_value(v):
    if isinstance(v, str):
        if v.startswith("Vector2(") or v in ("true", "false"):
            return v
        return '"%s"' % v.strip('"')
    if isinstance(v, bool):
        return "true" if v else "false"
    return repr(v)


lines = ['class_name MonsterDefs', 'extends RefCounted', '## Generated by tools/worldgen/gen_monster_defs.py — every monster kind by name (sprites and base stats).', '',
         'const DEFS := {']
seen = set()
for key, m in WF.MON.items():
    name = m["name"]
    if name in seen:
        continue
    seen.add(name)
    kinds = []
    for kind in m["kinds"]:
        path, off = WF.monster_frames(m["pack"], kind)
        kinds.append('["%s", %s]' % (path, round(off, 1)))
    props = ", ".join('"%s": %s' % (k, gd_value(v)) for k, v in m["props"].items())
    lines.append('\t"%s": {"variants": [%s], %s},' % (name, ", ".join(kinds), props))
lines.append('}')
out = os.path.join(ROOT, "scripts/data/monster_defs.gd")
with open(out, "w", encoding="utf-8", newline="\n") as f:
    f.write("\n".join(lines) + "\n")
print("monster defs:", len(seen))
